"""Export the deliberately small DESIGN.md frontmatter to CSS, without dependencies."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def css_tokens():
    frontmatter = (ROOT / "DESIGN.md").read_text(encoding="utf-8").split("---", 2)[1]
    section = None
    type_role = None
    lines = ["/* Generated by generate_tokens.py from DESIGN.md. */", ":root {"]
    for line in frontmatter.splitlines():
        if match := re.fullmatch(r"(colors|typography|rounded|spacing):", line):
            section = match[1]
            continue
        if line and not line.startswith(" "):
            section = None
        if section == "typography":
            if match := re.fullmatch(r"  ([\w-]+):", line):
                type_role = match[1]
            elif match := re.fullmatch(r"    fontFamily: '(.*)'", line):
                lines.append(f"  --font-{type_role}: {match[1]};")
        elif section and (match := re.fullmatch(r'  ([\w-]+): "(.*)"', line)):
            prefix = {"colors": "color", "rounded": "radius", "spacing": "space"}[section]
            lines.append(f"  --{prefix}-{match[1]}: {match[2]};")
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "web" / "tokens.css"
    expected = css_tokens()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            raise SystemExit("Token CSS has drifted. Run python generate_tokens.py.")
        print("Design tokens match DESIGN.md.")
    else:
        target.parent.mkdir(exist_ok=True)
        target.write_text(expected, encoding="utf-8")
